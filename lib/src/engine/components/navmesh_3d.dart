/// Holds a baked 3D [nav3.NavPolygonMesh] and [nav3.NavMeshQuery] on a [GameObject] (E52-2).
final class NavMeshSurfaceComponent extends Behaviour {
  nav3.NavPolygonMesh? _mesh;
  nav3.NavMeshQuery? _query;

  double maxStepHeight;
  double maxSlopeDegrees;

  NavMeshSurfaceComponent({
    nav3.NavPolygonMesh? mesh,
    this.maxStepHeight = 0.6,
    this.maxSlopeDegrees = 45.0,
  })  : _mesh = mesh,
        _query = mesh == null ? null : nav3.NavMeshQuery(mesh);

  static final spec = ComponentSpec<NavMeshSurfaceComponent>(
    'NavMeshSurfaceComponent',
    NavMeshSurfaceComponent.new,
    [
      Field.number('maxStepHeight', (n) => n.maxStepHeight, (n, v) => n.maxStepHeight = v),
      Field.number('maxSlopeDegrees', (n) => n.maxSlopeDegrees, (n, v) => n.maxSlopeDegrees = v),
    ],
  );

  nav3.NavPolygonMesh? get mesh => _mesh;
  nav3.NavMeshQuery? get query => _query;
  int get polygonCount => _mesh?.polygons.length ?? 0;
  int get offMeshLinkCount => _mesh?.offMeshLinks.length ?? 0;

  void setMesh(nav3.NavPolygonMesh nextMesh) {
    _mesh = nextMesh;
    _query = nav3.NavMeshQuery(nextMesh);
  }

  /// Bakes a heightfield grid into maximal convex 3D polygons.
  void bakeFromHeightfield({
    required int columns,
    required int rows,
    required double cellSize,
    Vec3 origin = Vec3.zero,
    required bool Function(int col, int row) isWalkable,
    double Function(int col, int row)? sampleHeight,
    double Function(int col, int row)? sampleCost,
    int Function(int col, int row)? sampleFlags,
    List<nav3.NavOffMeshLink>? offMeshLinks,
  }) {
    final baked = nav3.NavMeshBuilder.fromHeightfield(
      columns: columns,
      rows: rows,
      cellSize: cellSize,
      origin: nav3.NavVec3(origin.x, origin.y, origin.z),
      isWalkable: isWalkable,
      sampleHeight: sampleHeight,
      sampleCost: sampleCost,
      sampleFlags: sampleFlags,
      maxStepHeight: maxStepHeight,
      maxSlopeDegrees: maxSlopeDegrees,
      offMeshLinks: offMeshLinks,
    );
    setMesh(baked);
  }

  /// Bakes a polygon NavMesh directly from an attached or provided [TerrainComponent].
  void bakeFromTerrain(
    TerrainComponent terrain, {
    required int columns,
    required int rows,
    required double cellSize,
    Vec3 origin = Vec3.zero,
    double minWalkableHeight = double.negativeInfinity,
    List<nav3.NavOffMeshLink>? offMeshLinks,
  }) {
    bakeFromHeightfield(
      columns: columns,
      rows: rows,
      cellSize: cellSize,
      origin: origin,
      isWalkable: (c, r) {
        final wx = origin.x + (c + 0.5) * cellSize;
        final wz = origin.z + (r + 0.5) * cellSize;
        return terrain.sampleHeight(wx, wz) >= minWalkableHeight;
      },
      sampleHeight: (c, r) {
        final wx = origin.x + c * cellSize;
        final wz = origin.z + r * cellSize;
        return terrain.sampleHeight(wx, wz);
      },
      offMeshLinks: offMeshLinks,
    );
  }

  /// Bakes a [nav3.NavPolygonMesh] directly from explicit convex 3D polygon loops.
  void bakeFromPolygons(
    List<List<Vec3>> polygonLoops, {
    List<double>? areaCosts,
    List<int>? areaFlags,
    List<nav3.NavOffMeshLink>? offMeshLinks,
  }) {
    final converted = polygonLoops
        .map((poly) => poly.map((v) => nav3.NavVec3(v.x, v.y, v.z)).toList())
        .toList();
    setMesh(nav3.NavMeshBuilder.fromPolygons(
      converted,
      areaCosts: areaCosts,
      areaFlags: areaFlags,
      offMeshLinks: offMeshLinks,
      stepTolerance: maxStepHeight,
    ));
  }

  void addOffMeshLink(nav3.NavOffMeshLink link) {
    _mesh?.addOffMeshLink(link);
  }

  nav3.NavPathResult findPath(
    Vec3 start,
    Vec3 goal, {
    int areaMask = -1,
    double maxYDiff = 5.0,
  }) {
    final q = _query;
    if (q == null) return nav3.NavPathResult.empty;
    return q.findPath(
      nav3.NavVec3(start.x, start.y, start.z),
      nav3.NavVec3(goal.x, goal.y, goal.z),
      areaMask: areaMask,
      maxYDiff: maxYDiff,
    );
  }
}

/// Navigates its owning [GameObject] along string-pulled [nav3.NavPathResult] waypoints
/// generated by a scene [NavMeshSurfaceComponent] (E52-2).
final class NavMeshAgent3DComponent extends Behaviour {
  NavMeshSurfaceComponent? surface;
  double speed;
  double angularSpeed;
  double stoppingDistance;
  int areaMask;
  bool alignToVelocity;
  double heightOffset;

  void Function(nav3.NavOffMeshLink link)? onTraverseOffMeshLink;
  void Function()? onDestinationReached;

  nav3.NavPathResult _currentPath = nav3.NavPathResult.empty;
  int _waypointIndex = 0;
  bool _hasActiveDestination = false;
  Vec3 _destination = Vec3.zero;
  nav3.NavOffMeshLink? _lastDispatchedLink;

  NavMeshAgent3DComponent({
    this.surface,
    this.speed = 4.5,
    this.angularSpeed = 12.0,
    this.stoppingDistance = 0.1,
    this.areaMask = -1,
    this.alignToVelocity = true,
    this.heightOffset = 0.0,
    this.onTraverseOffMeshLink,
    this.onDestinationReached,
  });

  static final spec = ComponentSpec<NavMeshAgent3DComponent>(
    'NavMeshAgent3DComponent',
    NavMeshAgent3DComponent.new,
    [
      Field.number('speed', (a) => a.speed, (a, v) => a.speed = v),
      Field.number('angularSpeed', (a) => a.angularSpeed, (a, v) => a.angularSpeed = v),
      Field.number('stoppingDistance', (a) => a.stoppingDistance, (a, v) => a.stoppingDistance = v),
      Field.integer('areaMask', (a) => a.areaMask, (a, v) => a.areaMask = v),
      Field.boolean('alignToVelocity', (a) => a.alignToVelocity, (a, v) => a.alignToVelocity = v),
      Field.number('heightOffset', (a) => a.heightOffset, (a, v) => a.heightOffset = v),
    ],
  );

  bool get hasPath => _hasActiveDestination && _currentPath.found;
  nav3.NavPathResult get currentPath => _currentPath;
  int get waypointIndex => _waypointIndex;
  Vec3 get destination => _destination;

  double get remainingDistance {
    if (!hasPath || _waypointIndex >= _currentPath.waypoints.length) return 0.0;
    var dist = 0.0;
    var prev = transform.position;
    for (int i = _waypointIndex; i < _currentPath.waypoints.length; i++) {
      final wp = _currentPath.waypoints[i].position;
      final v = Vec3(wp.x, wp.y + heightOffset, wp.z);
      dist += (v - prev).length;
      prev = v;
    }
    return dist;
  }

  /// Plans a funnel-smoothed 3D path from current position to [target] and starts moving.
  bool setDestination(Vec3 target) {
    final surf = surface ?? (isAttached ? scene.findObjectOfType<NavMeshSurfaceComponent>() : null);
    if (surf == null) return false;
    surface = surf;

    final origin = isAttached ? transform.position : Vec3.zero;
    final res = surf.findPath(origin, target, areaMask: areaMask);
    _currentPath = res;
    _destination = target;
    _lastDispatchedLink = null;
    if (!res.found || res.waypoints.isEmpty) {
      _hasActiveDestination = false;
      _waypointIndex = 0;
      return false;
    }
    _hasActiveDestination = true;
    // Skip index 0 if agent is already standing right at start projection.
    _waypointIndex = res.waypoints.length > 1 ? 1 : 0;
    return true;
  }

  void stopPath() {
    _hasActiveDestination = false;
    _currentPath = nav3.NavPathResult.empty;
    _waypointIndex = 0;
    _lastDispatchedLink = null;
  }

  @override
  void start() {
    if (surface == null && isAttached) {
      surface = scene.findObjectOfType<NavMeshSurfaceComponent>();
    }
  }

  @override
  void update() {
    if (!hasPath || _waypointIndex >= _currentPath.waypoints.length) return;
    final dt = time.deltaTime;
    if (dt <= 0.0) return;

    var remainingMove = speed * dt;
    while (remainingMove > 1e-6 && _waypointIndex < _currentPath.waypoints.length) {
      final wp = _currentPath.waypoints[_waypointIndex];
      final targetPos = Vec3(wp.position.x, wp.position.y + heightOffset, wp.position.z);
      final delta = targetPos - transform.position;
      final dist = delta.length;

      if (wp.offMeshLink != null && !identical(wp.offMeshLink, _lastDispatchedLink)) {
        _lastDispatchedLink = wp.offMeshLink;
        onTraverseOffMeshLink?.call(wp.offMeshLink!);
      }

      final isFinal = _waypointIndex == _currentPath.waypoints.length - 1;
      if (isFinal && dist <= math.max(1e-4, stoppingDistance)) {
        transform.position = targetPos;
        _hasActiveDestination = false;
        onDestinationReached?.call();
        return;
      }

      if (dist <= remainingMove) {
        transform.position = targetPos;
        remainingMove -= dist;
        _waypointIndex++;
        if (_waypointIndex >= _currentPath.waypoints.length) {
          _hasActiveDestination = false;
          onDestinationReached?.call();
          return;
        }
      } else {
        final dir = delta * (1.0 / dist);
        transform.position = transform.position + dir * remainingMove;
        if (alignToVelocity) {
          final flatDir = Vec3(dir.x, 0.0, dir.z);
          if (flatDir.lengthSquared > 1e-6) {
            final targetRot = lookRotation(flatDir);
            transform.rotation = Quat.slerp(
              transform.rotation,
              targetRot,
              (angularSpeed * dt).clamp(0.0, 1.0),
            );
          }
        }
        remainingMove = 0.0;
      }
    }
  }
}

/// Immediate-mode `voxui` NavMesh polygon & agent corridor inspector (E52-2).
final class NavMeshDebuggerUI {
  static void render(
    VoxUiContext ui,
    NavMeshSurfaceComponent surface, {
    NavMeshAgent3DComponent? agent,
    String title = '3D NavMesh Inspector',
    double x = 20.0,
    double y = 20.0,
    double width = 350.0,
    double height = 240.0,
  }) {
    if (!ui.beginWindow(title, x: x, y: y, width: width, height: height)) {
      ui.endWindow();
      return;
    }

    final mesh = surface.mesh;
    var portalTotal = 0;
    if (mesh != null) {
      for (final p in mesh.polygons) {
        portalTotal += p.portals.length;
      }
    }

    ui.labelValue('Polygons', '${surface.polygonCount}', valueColor: VoxColor.cyan);
    ui.labelValue('Shared Portals', '${portalTotal ~/ 2}', valueColor: VoxColor.lightGray);
    ui.labelValue('Off-Mesh Links', '${surface.offMeshLinkCount}', valueColor: VoxColor.yellow);

    if (agent != null) {
      ui.separator();
      ui.labelValue(
        'Agent Status',
        agent.hasPath ? 'Navigating' : 'Idle',
        valueColor: agent.hasPath ? VoxColor.green : VoxColor.gray,
      );
      ui.labelValue(
        'Waypoints',
        '${agent.waypointIndex} / ${agent.currentPath.waypoints.length}',
        valueColor: VoxColor.cyan,
      );
      ui.labelValue(
        'Remaining Dist',
        '${agent.remainingDistance.toStringAsFixed(2)}m',
        valueColor: VoxColor.lightGray,
      );
      if (agent.hasPath && ui.button('Clear Agent Path', height: 20.0)) {
        agent.stopPath();
      }
    }

    ui.endWindow();
  }
}
