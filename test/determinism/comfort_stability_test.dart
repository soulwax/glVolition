// Accessibility Comfort Profile Model & Controller
// ============================================================================

enum ComfortTier { unrestricted, reducedMotion, maximumComfort }

final class AccessibilityComfortProfile {
  ComfortTier tier;
  double maxVignette;
  double maxChromaticAberration;
  double cameraShakeTranslationScale;
  double cameraShakeRotationScale;
  double maxFlashIntensity;
  double minFlashCooldownSeconds;

  AccessibilityComfortProfile.unrestricted()
    : tier = ComfortTier.unrestricted,
      maxVignette = 1.0,
      maxChromaticAberration = 1.0,
      cameraShakeTranslationScale = 1.0,
      cameraShakeRotationScale = 1.0,
      maxFlashIntensity = 1.0,
      minFlashCooldownSeconds = 0.0;

  AccessibilityComfortProfile.reducedMotion()
    : tier = ComfortTier.reducedMotion,
      maxVignette = 0.25,
      maxChromaticAberration = 0.0,
      cameraShakeTranslationScale = 0.0,
      cameraShakeRotationScale = 0.0,
      maxFlashIntensity = 0.3,
      minFlashCooldownSeconds = 0.25;

  AccessibilityComfortProfile.maximumComfort()
    : tier = ComfortTier.maximumComfort,
      maxVignette = 0.15,
      maxChromaticAberration = 0.0,
      cameraShakeTranslationScale = 0.0,
      cameraShakeRotationScale = 0.0,
      maxFlashIntensity = 0.05, // Below 0.10 WCAG threshold
      minFlashCooldownSeconds = 0.50;

  /// Applies this comfort profile dynamically to the scene and camera without restart.
  void applyTo(Scene scene, {Camera? camera}) {
    final rs = scene.renderSettings;
    final currentPost = rs.post;

    final isReduced = tier != ComfortTier.unrestricted;
    final clampedVignette = math.min(currentPost.vignette, maxVignette);
    final clampedChroma = math.min(
      currentPost.vhsChromaWeight,
      maxChromaticAberration,
    );

    rs.post = currentPost.copyWith(
      reducedMotion: isReduced,
      vignette: clampedVignette,
      vhsChromaWeight: clampedChroma,
    );

    if (camera != null) {
      if (isReduced) {
        camera.shakeEngine.maxTranslation = 0.20 * cameraShakeTranslationScale;
        camera.shakeEngine.rotationScale = cameraShakeRotationScale;
      } else {
        camera.shakeEngine.maxTranslation = 0.20;
        camera.shakeEngine.rotationScale = 1.0;
      }
    }
  }

  /// Clamps requested flash impulses to photosensitive safe thresholds.
  double clampFlash(double requestedStrength, double secondsSinceLastFlash) {
    if (secondsSinceLastFlash < minFlashCooldownSeconds) {
      return 0.0; // Suppress high-frequency strobes completely
    }
    return math.min(requestedStrength, maxFlashIntensity);
  }
}

// ============================================================================
// Visual Stability Auditor (Zero Jitter & Finite Number Checks)
// ============================================================================

abstract final class VisualStabilityAuditor {
  static void auditScene(Scene scene) {
    for (final go in scene.rootGameObjects) {
      _auditGameObject(go);
    }

    final rs = scene.renderSettings;
    expect(rs.ambientColor.r.isFinite, isTrue);
    expect(rs.ambientColor.g.isFinite, isTrue);
    expect(rs.ambientColor.b.isFinite, isTrue);
    expect(rs.ambientIntensity.isFinite, isTrue);
    expect(rs.fogStart.isFinite, isTrue);
    expect(rs.fogEnd.isFinite, isTrue);

    final post = rs.post;
    expect(post.exposure.isFinite, isTrue);
    expect(post.bloomStrength.isFinite, isTrue);
    expect(post.ssaoStrength.isFinite, isTrue);
    expect(post.vignette.isFinite, isTrue);
    expect(post.grain.isFinite, isTrue);
    expect(post.vhsTrackingWeight.isFinite, isTrue);
    expect(post.vhsChromaWeight.isFinite, isTrue);
    expect(post.vhsNoiseWeight.isFinite, isTrue);
  }

  static void _auditGameObject(GameObject go) {
    final pos = go.transform.position;
    final rot = go.transform.rotation;
    final scale = go.transform.localScale;

    expect(pos.x.isFinite, isTrue, reason: '${go.name}.pos.x not finite');
    expect(pos.y.isFinite, isTrue, reason: '${go.name}.pos.y not finite');
    expect(pos.z.isFinite, isTrue, reason: '${go.name}.pos.z not finite');

    expect(rot.x.isFinite, isTrue, reason: '${go.name}.rot.x not finite');
    expect(rot.y.isFinite, isTrue, reason: '${go.name}.rot.y not finite');
    expect(rot.z.isFinite, isTrue, reason: '${go.name}.rot.z not finite');
    expect(rot.w.isFinite, isTrue, reason: '${go.name}.rot.w not finite');

    expect(scale.isFinite, isTrue, reason: '${go.name}.scale not finite');

    final rb = go.getComponent<RigidBody>();
    if (rb != null) {
      expect(rb.velocity.x.isFinite, isTrue);
      expect(rb.velocity.y.isFinite, isTrue);
      expect(rb.velocity.z.isFinite, isTrue);
      expect(rb.mass.isFinite, isTrue);
    }

    final cam = go.getComponent<Camera>();
    if (cam != null) {
      final view = cam.toCameraView(16.0 / 9.0);
      for (var i = 0; i < 16; i++) {
        expect(
          view.view.m[i].isFinite,
          isTrue,
          reason: 'viewMatrix[$i] not finite',
        );
        expect(
          view.projection.m[i].isFinite,
          isTrue,
          reason: 'projectionMatrix[$i] not finite',
        );
      }
    }

    for (final child in go.children) {
      _auditGameObject(child);
    }
  }
}

