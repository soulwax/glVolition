// Automated Luminance & Photosensitivity Flash-Rate Safety Gate (ITU-R / WCAG)
// ============================================================================

/// Represents a detected flash transition (a pair of opposing changes in relative luminance >= 0.10).
final class FlashEvent {
  final double timestamp;
  final double startLuminance;
  final double peakLuminance;
  final double endLuminance;
  final bool isRedFlash;

  const FlashEvent({
    required this.timestamp,
    required this.startLuminance,
    required this.peakLuminance,
    required this.endLuminance,
    this.isRedFlash = false,
  });

  double get deltaLuminance =>
      (peakLuminance - math.min(startLuminance, endLuminance)).abs();
}

/// Evaluation result generated by [PhotosensitivityFlashDetector].
final class FlashSafetyReport {
  final bool isSafe;
  final int totalFlashes;
  final int maxFlashesInOneSecondWindow;
  final double maxFlashesPerSecondRate;
  final List<String> violations;

  const FlashSafetyReport({
    required this.isSafe,
    required this.totalFlashes,
    required this.maxFlashesInOneSecondWindow,
    required this.maxFlashesPerSecondRate,
    required this.violations,
  });
}

/// Automated ITU-R BT.1702 and WCAG 2.1 (Success Criterion 2.3.1: Three Flashes or Below Threshold)
/// safety detector for photosensitive epilepsy prevention.
final class PhotosensitivityFlashDetector {
  final double minLuminanceDelta;
  final double maxDarkLuminance;
  final int maxFlashesPerSecondThreshold; // 3 flashes/sec limit

  final List<({double time, double lum, bool isSaturatedRed})> _samples = [];
  final List<FlashEvent> _flashes = [];

  PhotosensitivityFlashDetector({
    this.minLuminanceDelta = 0.10,
    this.maxDarkLuminance = 0.80,
    this.maxFlashesPerSecondThreshold = 3,
  });

  /// Computes WCAG / ITU-R relative luminance from sRGB values in [0.0, 1.0].
  static double relativeLuminanceFromRgb(double r, double g, double b) {
    final cr = r.clamp(0.0, 1.0);
    final cg = g.clamp(0.0, 1.0);
    final cb = b.clamp(0.0, 1.0);
    return 0.2126 * cr + 0.7152 * cg + 0.0722 * cb;
  }

  void addLuminanceSample(double timeSeconds, double luminance) {
    _samples.add((
      time: timeSeconds,
      lum: luminance.clamp(0.0, 1.0),
      isSaturatedRed: false,
    ));
    _analyzeStream();
  }

  void addRgbSample(double timeSeconds, double r, double g, double b) {
    final lum = relativeLuminanceFromRgb(r, g, b);
    final total = r + g + b;
    final isSaturatedRed = total > 0.05 && (r / total) >= 0.80;
    _samples.add((time: timeSeconds, lum: lum, isSaturatedRed: isSaturatedRed));
    _analyzeStream();
  }

  void _analyzeStream() {
    if (_samples.length < 3) return;

    // Detect turning points (peaks and valleys)
    final n = _samples.length;
    final prev = _samples[n - 3];
    final mid = _samples[n - 2];
    final curr = _samples[n - 1];

    final d1 = mid.lum - prev.lum;
    final d2 = curr.lum - mid.lum;

    // Turning point at mid: slope changed sign or reached flat peak
    final isPeak = d1 > 0.001 && d2 <= 0.001;
    final isValley = d1 < -0.001 && d2 >= -0.001;

    if (isPeak || isValley) {
      _checkRecentTransition(mid.time);
    }
  }

  void _checkRecentTransition(double midTime) {
    // Find min and max within recent 0.35s window
    final windowStart = midTime - 0.35;
    var minLum = 1.0;
    var maxLum = 0.0;
    var hasRed = false;

    for (var i = _samples.length - 1; i >= 0; i--) {
      final s = _samples[i];
      if (s.time < windowStart) break;
      if (s.lum < minLum) minLum = s.lum;
      if (s.lum > maxLum) maxLum = s.lum;
      if (s.isSaturatedRed) hasRed = true;
    }

    final delta = maxLum - minLum;
    if (delta >= minLuminanceDelta && minLum < maxDarkLuminance) {
      // Avoid duplicate flash detections within 0.08s of an existing flash
      if (_flashes.isEmpty || (midTime - _flashes.last.timestamp) >= 0.08) {
        _flashes.add(
          FlashEvent(
            timestamp: midTime,
            startLuminance: minLum,
            peakLuminance: maxLum,
            endLuminance: minLum,
            isRedFlash: hasRed,
          ),
        );
      }
    }
  }

  FlashSafetyReport evaluate() {
    var maxFlashesInWindow = 0;
    final violations = <String>[];

    for (var i = 0; i < _flashes.length; i++) {
      final flash = _flashes[i];
      final windowStart = flash.timestamp - 1.0;
      var count = 0;

      for (var j = 0; j <= i; j++) {
        if (_flashes[j].timestamp >= windowStart) {
          count++;
        }
      }

      if (count > maxFlashesInWindow) {
        maxFlashesInWindow = count;
      }

      if (count > maxFlashesPerSecondThreshold) {
        violations.add(
          'Unsafe flash frequency: $count flashes within 1.0s window ending at t=${flash.timestamp.toStringAsFixed(3)}s (threshold: $maxFlashesPerSecondThreshold)',
        );
      }

      if (flash.isRedFlash && flash.deltaLuminance >= minLuminanceDelta) {
        violations.add(
          'Unsafe saturated red flash detected at t=${flash.timestamp.toStringAsFixed(3)}s (delta=${flash.deltaLuminance.toStringAsFixed(2)})',
        );
      }
    }

    final duration = _samples.isEmpty
        ? 1.0
        : math.max(0.001, _samples.last.time - _samples.first.time);
    final rate = _flashes.length / duration;

    final isSafe = violations.isEmpty;
    return FlashSafetyReport(
      isSafe: isSafe,
      totalFlashes: _flashes.length,
      maxFlashesInOneSecondWindow: maxFlashesInWindow,
      maxFlashesPerSecondRate: rate,
      violations: violations,
    );
  }
}

